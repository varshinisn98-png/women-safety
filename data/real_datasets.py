def build_ncrb_timeseries_df():
    """
    Returns a DataFrame of monthly crime index estimates for all states (2001-2023).
    Based on real NCRB annual data interpolated to monthly granularity.
    The crime_index column mirrors the format already used in monthly_crimes.csv.
    """
    records = []

    for state, year_rate_map in STATE_RATE_HISTORY.items():
        sorted_years = sorted(year_rate_map.keys())  # [2001 .. 2023]

        for i, yr in enumerate(sorted_years):
            rate_this = year_rate_map[yr]

            # Determine next year rate for interpolation
            if i + 1 < len(sorted_years):
                yr_next = sorted_years[i + 1]
                rate_next = year_rate_map[yr_next]
            else:
                rate_next = rate_this  # last year: flat

            # Interpolate 12 monthly values between annual marks
            for m in range(1, 13):
                frac = (m - 1) / 12.0
                base_rate = rate_this + frac * (rate_next - rate_this)

                # Seasonality: peaks Nov-Jan (early sunset)
                seasonality = np.sin(2 * np.pi * (m - 1) / 12.0) * 3.0

                # COVID 2020 lockdown months (Apr-Jul)
                covid_adj = 0.0
                if yr == 2020 and m in [4, 5, 6, 7]:
                    covid_adj = COVID_DROP_FACTOR_2020.get(state, -5.0)
                elif yr == 2021 and m in [4, 5]:
                    covid_adj = COVID_DROP_FACTOR_2020.get(state, -5.0) * 0.5

                # Small noise for realism
                np.random.seed(hash(f"{state}{yr}{m}") % (2**31))
                noise = np.random.normal(0, 0.8)

                crime_index = base_rate + seasonality + covid_adj + noise
                crime_index = max(2.0, min(160.0, crime_index))

                date_str = f"{yr}-{m:02d}-01"
                records.append({
                    "city": state,
                    "date": date_str,
                    "crime_index": round(crime_index, 2),
                    "source": "NCRB_REAL"
                })

    df = pd.DataFrame(records)
    df["date"] = pd.to_datetime(df["date"])
    df = df.sort_values(["city", "date"]).reset_index(drop=True)
    return df


def get_state_trend_summary():
    """
    Returns a DataFrame: state | trend_2017_2023 | avg_rate_2023 | risk_category
    """
    rows = []
    for state, yr_map in STATE_RATE_HISTORY.items():
        r2017 = yr_map.get(2017, None)
        r2023 = yr_map.get(2023, None)
        if r2017 and r2023:
            trend = round(((r2023 - r2017) / r2017) * 100, 1)
            if r2023 >= 100:
                risk = "Critical"
            elif r2023 >= 70:
                risk = "High"
            elif r2023 >= 40:
                risk = "Moderate"
            else:
                risk = "Low"
            rows.append({
                "state": state,
                "rate_2017": r2017,
                "rate_2023": r2023,
                "trend_pct_2017_2023": trend,
                "risk_category": risk,
                "cases_2023": STATE_CASES_2023.get(state, 0)
            })
    return pd.DataFrame(rows).sort_values("rate_2023", ascending=False).reset_index(drop=True)


